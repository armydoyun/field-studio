// npm install && npm run build  →  ../../js/codemirror.js
// esbuild로 IIFE 하나를 만든 뒤, 앱의 정적 ES Module 형식(맨 끝 `export { … };`)으로 감싼다.
// tools/build_deploy.py와 테스트 하네스는 이 형식만 읽는다.
import {build} from "esbuild";
import {readFileSync, writeFileSync} from "node:fs";
const names = [...readFileSync(new URL("./entry.js", import.meta.url), "utf8").matchAll(/export \{([^}]+)\}/g)].flatMap(m => m[1].split(",").map(s => s.trim()).filter(Boolean));
const result = await build({entryPoints:[new URL("./entry.js", import.meta.url).pathname], bundle:true, minify:true, format:"iife", globalName:"__CodeMirror", write:false, legalComments:"none", target:"es2020"});
const pkg = name => JSON.parse(readFileSync(new URL(`./node_modules/${name}/package.json`, import.meta.url), "utf8"));
const versions = ["@codemirror/state","@codemirror/view","@codemirror/commands","@codemirror/language","@codemirror/search","@codemirror/autocomplete","@codemirror/lint","@lezer/common","@lezer/highlight","style-mod","w3c-keyname","crelt"].map(n => `${n}@${pkg(n).version}`).join(", ");
const header = `// CodeMirror 6 vendored bundle for FIELD Studio — generated by tools/codemirror/build.mjs. Do not edit by hand.
// ${versions}
// Copyright (C) 2018-2021 by Marijn Haverbeke <marijn@haverbeke.berlin> and others. MIT License (see tools/codemirror/LICENSE).
`;
// CodeMirror는 불러오는 순간 document에 스타일을 등록한다. 기본 편집기만 쓸 때는 실행되지 않도록 load()를 처음 부를 때 초기화한다.
const code = result.outputFiles[0].text.trim(), prefix = "var __CodeMirror=";
if(!code.startsWith(prefix) || !code.endsWith(";")) throw new Error("unexpected esbuild IIFE shape");
const factory = code.slice(prefix.length, -1);
writeFileSync(new URL("../../js/codemirror.js", import.meta.url), `${header}// API: load() → { ${names.join(", ")} }\nlet loaded = null;\nconst load = () => loaded || (loaded = ${factory});\nexport { load };\n`);
console.log(`js/codemirror.js: load() with ${names.length} names`);
